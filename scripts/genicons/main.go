// genicons 从 @ant-design/icons 的 SVG 生成 icon/icons_gen.go。
//
// 用法：下载 SVG 到临时目录后运行
//
//	go run ./scripts/genicons <svg 目录> <输出文件>
//
// 生成规则：给 <svg> 根元素加 fill="currentColor"（跟随文本色），
// 图标名转 PascalCase 导出常量。
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "用法: genicons <svg目录> <输出文件>")
		os.Exit(1)
	}
	dir, out := os.Args[1], os.Args[2]
	entries, err := os.ReadDir(dir)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}

	type icon struct{ name, svg string }
	var icons []icon
	seen := map[string]bool{}
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".svg") {
			continue
		}
		data, err := os.ReadFile(filepath.Join(dir, e.Name()))
		if err != nil || len(data) == 0 {
			continue
		}
		svg := strings.TrimSpace(string(data))
		// 根元素加 fill="currentColor"，让图标随 ui 文本色变化。
		svg = strings.Replace(svg, "<svg ", "<svg fill=\"currentColor\" ", 1)
		svg = strings.ReplaceAll(svg, "\n", "")
		name := pascal(strings.TrimSuffix(e.Name(), ".svg"))
		if name == "" || seen[name] {
			continue
		}
		seen[name] = true
		icons = append(icons, icon{name, svg})
	}
	sort.Slice(icons, func(i, j int) bool { return icons[i].name < icons[j].name })

	var b strings.Builder
	b.WriteString("// Code generated by scripts/genicons from @ant-design/icons. DO NOT EDIT.\n\n")
	b.WriteString("package icon\n\n")
	b.WriteString("// 图标 SVG 常量（outlined 子集，fill=currentColor 跟随文本色）。")
	b.WriteString("用 icon.Icon 渲染：\n//\n//\ticon.Icon(c, icon.Search, 16)\n//\n")
	b.WriteString("// 来源：github.com/ant-design/ant-design-icons（MIT License）。\n")
	b.WriteString("const (\n")
	for _, ic := range icons {
		b.WriteString(fmt.Sprintf("\t%s = `%s`\n", ic.name, ic.svg))
	}
	b.WriteString(")\n")
	if err := os.WriteFile(out, []byte(b.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Printf("生成 %d 个图标 → %s\n", len(icons), out)
}

// pascal 把 kebab-case 图标名转 PascalCase。
func pascal(s string) string {
	parts := strings.Split(s, "-")
	for i, p := range parts {
		if p == "" {
			return "" // 非法名跳过
		}
		parts[i] = strings.ToUpper(p[:1]) + p[1:]
	}
	return strings.Join(parts, "")
}
